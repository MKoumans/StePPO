def save_csv(path: str, series: dict) -> None:
    """Write {method: {column: 1-D array}} as one long-format CSV with a leading `method` column."""
    columns = list(dict.fromkeys(c for cols in series.values() for c in cols))
    with open(path, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["method"] + columns)
        for method, cols in series.items():
            n = len(next(iter(cols.values())))
            for i in range(n):
                writer.writerow(
                    [method] + [f"{cols[c][i]:.8g}" if c in cols else "" for c in columns]
                )
    print(f"[+] {path}")


